// bin2cpp — tiny build-time tool: turns a binary file into a C++ byte array.
// Usage: bin2cpp <file> <symbol>   (prints to stdout; runs before main build)
#include <cstdio>
#include <cstdlib>

int main(int argc, char** argv) {
    if (argc != 3) { fprintf(stderr, "usage: bin2cpp <file> <symbol>\n"); return 1; }
    FILE* f = fopen(argv[1], "rb");
    if (!f) { fprintf(stderr, "cannot open %s\n", argv[1]); return 1; }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char* buf = (unsigned char*)malloc(n ? n : 1);
    if (fread(buf, 1, (size_t)n, f) != (size_t)n && n > 0) { fprintf(stderr, "read error\n"); fclose(f); return 1; }
    fclose(f);
    printf("// generated by bin2cpp from %s — do not edit\n", argv[1]);
    printf("#include <cstddef>\nnamespace leptid_embed {\n");
    printf("extern const unsigned char %s[] = {", argv[2]);
    for (long i = 0; i < n; ++i) {
        if (i % 20 == 0) printf("\n ");
        printf("%u,", (unsigned)buf[i]);
    }
    printf("\n};\n");
    // NOTE: the length symbol is a plain (non-const) `unsigned int` and MUST
    // stay declared exactly that way in every consumer (ui.cpp/ui.h, brush.cpp,
    // editor.cpp, platform_x11.cpp). MSVC encodes the type into variable
    // symbols — a `const size_t` definition against an `extern const unsigned`
    // declaration mangles differently and fails with LNK2019 (the Linux/macOS
    // linkers do not mangle variable types, which is why it only broke on
    // Windows). Non-const also guarantees MSVC emits storage for it.
    printf("extern unsigned int %s_len = %ld;\n", argv[2], n);
    printf("}\n");
    free(buf);
    return 0;
}
